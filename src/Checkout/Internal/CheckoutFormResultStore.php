<?php

declare(strict_types=1);

namespace ProgrammatorDev\StripeCheckout\Checkout\Internal;

use Closure;
use DateTimeImmutable;
use Kirby\Session\Session;
use ProgrammatorDev\StripeCheckout\Checkout\CheckoutError;
use ProgrammatorDev\StripeCheckout\Checkout\CheckoutErrorCode;
use ProgrammatorDev\StripeCheckout\Checkout\Exception\CheckoutInputException;
use Throwable;

/**
 * Bounded native-session state for returning one safe form error to its initiating page.
 *
 * @internal
 */
final class CheckoutFormResultStore
{
    public const KEY = 'programmatordev.stripe-checkout.form-results';

    private const SCHEMA_VERSION = 1;

    private const MAX_RESULTS = 100;

    public function __construct(private readonly Session $session) {}

    public function save(
        CheckoutError $error,
        BrowserAttempt $attempt,
        ?CheckoutSubmissionInput $retryInput,
        DateTimeImmutable $savedAt,
        int $expiresAt,
    ): string {
        return $this->locked(function () use ($error, $attempt, $retryInput, $savedAt, $expiresAt): string {
            $results = $this->current($savedAt->getTimestamp());

            if (count($results) >= self::MAX_RESULTS) {
                foreach ($results as $hash => $resultData) {
                    if (CheckoutFormResult::fromArray($resultData)->retryInput() === null) {
                        unset($results[$hash]);
                        break;
                    }
                }
            }

            // Losing an exact retry could cause a later page render to issue a competing action.
            if (count($results) >= self::MAX_RESULTS) {
                throw new CheckoutInputException(CheckoutErrorCode::ATTEMPT_LIMIT_REACHED);
            }

            do {
                $reference = rtrim(strtr(base64_encode(random_bytes(32)), '+/', '-_'), '=');
                $hash = hash('sha256', $reference);
            } while (array_key_exists($hash, $results));

            $results[$hash] = (new CheckoutFormResult(
                error: $error,
                context: CheckoutFormResultContext::fromAttempt($attempt),
                retryInput: $retryInput,
                expiresAt: $expiresAt,
            ))->toArray();
            $this->write($results);

            return $reference;
        });
    }

    public function find(string $value, DateTimeImmutable $checkedAt): ?CheckoutFormResult
    {
        // References are generated by this store with fixed base64url encoding.
        // Reject unrelated query input before opening and rewriting session state.
        if (preg_match('/\A[A-Za-z0-9_-]{43}\z/D', $value) !== 1) {
            return null;
        }

        $hash = hash('sha256', $value);

        return $this->locked(function () use ($hash, $checkedAt): ?CheckoutFormResult {
            $results = $this->current($checkedAt->getTimestamp());
            $resultData = $results[$hash] ?? null;

            if ($resultData === null) {
                return null;
            }

            try {
                return CheckoutFormResult::fromArray($resultData);
            } catch (Throwable) {
                unset($results[$hash]);
                $this->write($results);

                return null;
            }
        });
    }

    /**
     * @template T
     * @param Closure(): T $operation
     * @return T
     */
    private function locked(Closure $operation): mixed
    {
        $this->session->ensureToken();
        $this->session->prepareForWriting();

        try {
            return $operation();
        } finally {
            $this->session->commit();
        }
    }

    /** @return array<string, array<string, mixed>> */
    private function current(int $checkedAt): array
    {
        $payload = $this->session->data()->get(self::KEY);
        $results = [];

        if (is_array($payload) && ($payload['schema'] ?? null) === self::SCHEMA_VERSION && is_array($payload['results'] ?? null)) {
            foreach ($payload['results'] as $hash => $resultData) {
                if (
                    is_string($hash) === false
                    || preg_match('/\A[a-f0-9]{64}\z/D', $hash) !== 1
                    || is_array($resultData) === false
                ) {
                    continue;
                }

                try {
                    $result = CheckoutFormResult::fromArray($resultData);
                } catch (Throwable) {
                    continue;
                }

                if ($checkedAt >= $result->expiresAt()) {
                    continue;
                }

                $results[$hash] = $result->toArray();
            }
        }

        $this->write($results);

        return $results;
    }

    /** @param array<string, array<string, mixed>> $results */
    private function write(array $results): void
    {
        $this->session->data()->set(self::KEY, [
            'schema' => self::SCHEMA_VERSION,
            'results' => $results,
        ]);
    }
}
